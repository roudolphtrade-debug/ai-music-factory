export type AuthCopy = Dict;
export type AuthKey = keyof Dict;
export const authCopy: Record<Lang, Dict> = { fr, en, es, zh, pt, ar };

/** Fills `{name}`-style placeholders; an unknown placeholder is left as written. */
export function fillCopy(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function authText(lang: Lang, key: AuthKey, vars?: Record<string, string | number>): string {
  return fillCopy(authCopy[lang][key], vars);
}

export function useAuthCopy() {
  const { lang } = useI18n();
  const t = (key: AuthKey, vars?: Record<string, string | number>) => authText(lang, key, vars);
  return { lang, t };
}
